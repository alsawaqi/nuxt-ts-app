const hasValue = (value) => value !== null && value !== undefined && String(value).trim() !== ''

const unique = (items) => [...new Set(items.filter(Boolean))]

const arabicFieldCandidates = (field) => {
  const lowerFirst = field.charAt(0).toLowerCase() + field.slice(1)

  return unique([
    `${field}_Ar`,
    `${field}_AR`,
    `${field}_ar`,
    `${lowerFirst}_ar`,
    `${lowerFirst}_Ar`,
    field.replace(/Name$/, 'Name_Ar'),
    field.replace(/Description$/, 'Description_Ar'),
    field.replace(/Title$/, 'Title_Ar'),
    field.replace(/Button_Text$/, 'Button_Text_Ar'),
    field === 'name' ? 'name_ar' : null,
    field === 'title' ? 'title_ar' : null,
    field === 'description' ? 'description_ar' : null,
    field === 'Search_Title' ? 'Search_Title_Ar' : null,
    field === 'Search_Subtitle' ? 'Search_Subtitle_Ar' : null,
  ])
}

const pickFirst = (source, fields) => {
  if (!source) return ''

  for (const field of fields) {
    if (hasValue(source[field])) return String(source[field]).trim()
  }

  return ''
}

export const isSupportedLocale = (locale) => supportedLocales.includes(locale)

export const normalizeLocale = (locale) => (isSupportedLocale(locale) ? locale : 'en')

export const directionFor = (locale) => localeMeta[normalizeLocale(locale)].dir

export const interpolate = (text, params = {}) => String(text).replace(/\{(\w+)\}/g, (_, key) => {
  return params[key] === null || params[key] === undefined ? '' : String(params[key])
})

export const t = (key, locale = 'en', params = {}) => {
  const current = normalizeLocale(locale)
  const template = messages[current]?.[key] ?? messages.en[key] ?? key

  return interpolate(template, params)
}

export const localizedField = (source, fields, locale = 'en', fallback = '') => {
  const baseFields = Array.isArray(fields) ? fields : [fields]
  const current = normalizeLocale(locale)

  if (current === 'ar') {
    const arabicFields = baseFields.flatMap(arabicFieldCandidates)
    const arabicValue = pickFirst(source, arabicFields)
    if (arabicValue) return arabicValue
  }

  const baseValue = pickFirst(source, baseFields)
  if (baseValue) return baseValue

  if (current !== 'ar') {
    const arabicFields = baseFields.flatMap(arabicFieldCandidates)
    const arabicValue = pickFirst(source, arabicFields)
    if (arabicValue) return arabicValue
  }

  return fallback
}

